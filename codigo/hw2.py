def cross_validate_pls(X_train, y_train, max_components=11, k=5, random_state=42):

    X_arr = np.array(X_train, dtype=float)
    y_arr = np.array(y_train, dtype=float).flatten()

    kf = KFold(n_splits=k, shuffle=True, random_state=random_state)
    grid_records = []

    # Testar de 1 até max_components (no caso dos vinhos, de 1 a 11)
    for n_comp in range(1, max_components + 1):
        fold_rmses = []
        fold_r2s = []

        for train_idx, val_idx in kf.split(X_arr):
            X_tr, y_tr = X_arr[train_idx], y_arr[train_idx]
            X_val, y_val = X_arr[val_idx], y_arr[val_idx]

            # Ajuste do PLS
            pls = PLSRegression(n_components=n_comp)
            pls.fit(X_tr, y_tr)

            # Predição no fold de validação
            y_pred_val = pls.predict(X_val).flatten()
            residuals = y_val - y_pred_val

            # Métricas
            rmse_val = np.sqrt(np.mean(residuals ** 2))
            ss_res = np.sum(residuals ** 2)
            ss_tot = np.sum((y_val - np.mean(y_val)) ** 2)
            r2_val = 1.0 - (ss_res / ss_tot)

            fold_rmses.append(rmse_val)
            fold_r2s.append(r2_val)

        grid_records.append({
            'Num_Componentes': int(n_comp),
            'RMSE_mean': float(np.mean(fold_rmses)),
            'RMSE_std': float(np.std(fold_rmses, ddof=1)),
            'R2_mean': float(np.mean(fold_r2s)),
            'R2_std': float(np.std(fold_r2s, ddof=1))
        })

    df_results = pd.DataFrame(grid_records)

    best_idx = df_results['RMSE_mean'].idxmin()
    best_n_comp = int(df_results.loc[best_idx, 'Num_Componentes'])

    return df_results, best_n_comp

