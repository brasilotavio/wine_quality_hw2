"""Criando função de avaliação de regressão, que, dado uma matriz B^, avalia seu erro a partir de um conjunto de treino (x_train e y_train)"""

def evaluate_regression(beta_hat, X_test, y_test):

    y_true = np.array(y_test, dtype=float).reshape(-1, 1)

    y_pred = compute_matmul(X_test, beta_hat)

    residuals = y_true - y_pred

    rmse = np.sqrt(np.mean(residuals ** 2))

    ss_res = np.sum(residuals ** 2)
    ss_tot = np.sum((y_true - np.mean(y_true)) ** 2)
    r2 = 1.0 - (ss_res / ss_tot)

    return float(rmse), float(r2), y_pred

