def cross_validation_ols(X, y, k=5, shuffle=True, random_state=42):

    y_vec = np.array(y, dtype=float).reshape(-1, 1)
    N = X.shape[0]


    indices = np.arange(N)
    if shuffle:
        rng = np.random.default_rng(random_state)
        indices = rng.permutation(indices)

    #Dividindo indices em K partes
    folds_indices = np.array_split(indices, k)

    fold_records = []


    for fold_num in range(k):

        val_idx = folds_indices[fold_num]


        train_idx = np.setdiff1d(indices, val_idx)

        X_tr, y_tr = X[train_idx], y_vec[train_idx]
        X_val, y_val = X[val_idx], y_vec[val_idx]


        beta_fold = fit_ols(X_tr, y_tr)


        rmse_val, r2_val, _ = evaluate_regression(beta_fold, X_val, y_val)

        fold_records.append({
            'Fold': fold_num + 1,
            'N_Treino': len(train_idx),
            'N_Validacao': len(val_idx),
            'RMSE': rmse_val,
            'R2': r2_val,
            'beta_hat': beta_fold
        })


    df_folds = pd.DataFrame(fold_records)


    best_idx = df_folds['RMSE'].idxmin()
    best_fold_info = df_folds.loc[best_idx].to_dict()

    cv_summary = {
        'K': k,
        'RMSE_mean': float(df_folds['RMSE'].mean()),
        'RMSE_std': float(df_folds['RMSE'].std()),
        'R2_mean': float(df_folds['R2'].mean()),
        'R2_std': float(df_folds['R2'].std())
    }

    return cv_summary, df_folds, best_fold_info

