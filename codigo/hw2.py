def standardize_features(X_train, X_test=None):

    # Converte para array numpy se for DataFrame
    is_df = isinstance(X_train, pd.DataFrame)
    columns = X_train.columns if is_df else None

    X_tr = np.array(X_train, dtype=float)


    mu = np.mean(X_tr, axis=0)
    sigma = np.std(X_tr, axis=0, ddof=0)


    sigma_adj = np.where(sigma == 0, 1.0, sigma)


    X_tr_scaled = (X_tr - mu) / sigma_adj

    scaler_params = {
        'mean': mu,
        'std': sigma,
        'feature_names': columns
    }


    if X_test is not None:
        X_ts = np.array(X_test, dtype=float)
        X_ts_scaled = (X_ts - mu) / sigma_adj

        if is_df:
            X_tr_scaled = pd.DataFrame(X_tr_scaled, columns=columns, index=X_train.index)
            X_ts_scaled = pd.DataFrame(X_ts_scaled, columns=columns, index=X_test.index)

        return X_tr_scaled, X_ts_scaled, scaler_params

    if is_df:
        X_tr_scaled = pd.DataFrame(X_tr_scaled, columns=columns, index=X_train.index)

    return X_tr_scaled, scaler_params

