"""Implementando Lasso na mão:"""

def soft_threshold(z, gamma):

    if z > gamma:
        return z - gamma
    elif z < -gamma:
        return z + gamma
    else:
        return 0.0


def fit_lasso_coordinate_descent(X, y, alpha=0.01, max_iter=2000, tol=1e-5):

    X_arr = np.array(X, dtype=float)
    y_arr = np.array(y, dtype=float).flatten()

    N, D = X_arr.shape


    y_mean = np.mean(y_arr)
    y_cent = y_arr - y_mean


    col_norm_sq = np.sum(X_arr ** 2, axis=0)


    beta = np.zeros(D, dtype=float)


    for iteration in range(max_iter):
        beta_old = beta.copy()

        for j in range(D):

            r_j = y_cent - (X_arr @ beta - X_arr[:, j] * beta[j])


            rho_j = np.dot(X_arr[:, j], r_j)


            beta[j] = soft_threshold(rho_j, N * alpha) / col_norm_sq[j]


        if np.max(np.abs(beta - beta_old)) < tol:
            break

    return y_mean, beta

