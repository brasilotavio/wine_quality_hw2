"""Funções para calcular inversa e transposta:"""

def compute_transpose(matrix):
    return np.transpose(matrix)  # ou matrix.T


def compute_inverse(matrix):
    return np.linalg.inv(matrix)

def compute_matmul(matrix_a, matrix_b):
    return np.matmul(matrix_a, matrix_b)  # ou matrix_a @ matrix_b

"""Juntando tudo em uma função que calcula OLS:"""

def fit_ols(X, Y, feature_names=None):
    # 1. X^T
    X_T = compute_transpose(X)

    # 2. X^T @ X
    XtX = compute_matmul(X_T, X)

    # 3. (X^T @ X)^(-1)
    XtX_inv = compute_inverse(XtX)

    # 4. X^T @ Y
    XtY = compute_matmul(X_T, Y)

    # 5. beta_hat = (X^T @ X)^(-1) @ (X^T @ Y)
    beta_hat = compute_matmul(XtX_inv, XtY)

    # Se uma lista de nomes for fornecida, organiza em DataFrame
    if feature_names is not None:
        names = ['intercept'] + list(feature_names) if len(feature_names) == (X.shape[1] - 1) else feature_names
        df_beta = pd.DataFrame({
            'Preditor': names,
            'Beta_Hat': beta_hat.flatten()
        })
        return beta_hat, df_beta

    return beta_hat

