"""Criando função responsável por montar a matriz de design:"""

def build_design_matrix(data, feature_cols=None, target_col=None, add_intercept=True):


    if isinstance(data, pd.DataFrame):
        if feature_cols is None:

            feature_cols = [c for c in data.columns if c != target_col]
        X = data[feature_cols].to_numpy(dtype=float)

        y = None
        if target_col is not None and target_col in data.columns:
            y = data[target_col].to_numpy(dtype=float).reshape(-1, 1)
    else:

        X = np.array(data, dtype=float)
        y = None

    # Concatenacao da coluna de '1' para o intercepto (beta 0)
    if add_intercept:
        N = X.shape[0]
        ones = np.ones((N, 1), dtype=float)
        X = np.hstack([ones, X])

    if y is not None:
        return X, y
    return X

